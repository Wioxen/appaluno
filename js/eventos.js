function obterPrimeiroUltimoNome(nomeCompleto) {
    // Remove espaços extras e divide a string em partes
    var partes = nomeCompleto.trim().split(/\s+/);
    
    // Verifica se há pelo menos 2 nomes
    if (partes.length < 2) {
        return nomeCompleto; // Retorna o nome original se não houver sobrenome
    }
    
    // Pega o primeiro e último nome
    var primeiroNome = partes[0];
    var ultimoNome = partes[partes.length - 1];
    
    return primeiroNome + ' ' + ultimoNome;
}